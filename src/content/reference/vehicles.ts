/** Volume ruang muat dari dimensi, bukan dari rentang perencanaan. */
export function cargoVolume(vehicle: VehicleArchetype): number | undefined {
  if (!vehicle.cargo) return undefined;
  return vehicle.cargo.length * vehicle.cargo.width * vehicle.cargo.height;
}

/**
 * Archetype yang layak jadi pilihan pada kalkulator muatan.
 *
 * Bodi tanpa ruang tertutup -- flatbed, tanker, lowbed, SPMT -- sengaja
 * disaring keluar. Kalkulator yang menawarkan "berapa kardus muat di tangki"
 * bukan sekadar tidak berguna; ia mengajarkan satuan kapasitas yang keliru
 * untuk bodi tersebut. Body_Types pada sumber data menyebutnya eksplisit:
 * tidak setiap kendaraan pantas dinyatakan dalam meter kubik.
 */
const NOT_CARTON_LOADABLE = new Set([
  // Container chassis: what gets loaded is the container, and the container
  // page already answers that question with the right internal dimensions.
  "CV035",
  "CV036",
  // Livestock: measured in head per deck area, never in cartons.
  "CV050",
]);

export function loadableArchetypes(): VehicleArchetype[] {
  return VEHICLE_ARCHETYPES.filter(
    (v) => v.cargo !== undefined && v.planningVolume !== undefined && !NOT_CARTON_LOADABLE.has(v.id),
  );
}

/**
 * Menjaga agar setiap kelas pada VEHICLE_CLASS_ORDER benar-benar ada, dan
 * sebaliknya. Kelas yang salah eja hanya akan menghilang dari halaman
 * referensi tanpa error -- persis jenis cacat yang tidak terlihat saat dibaca.
 */
function assertClassOrderIntegrity(): void {
  const present = new Set(VEHICLE_ARCHETYPES.map((v) => v.mainClass));
  const ordered = new Set(VEHICLE_CLASS_ORDER);

  for (const cls of present) {
    if (!ordered.has(cls)) throw new Error(`Vehicle class "${cls}" is missing from VEHICLE_CLASS_ORDER`);
  }
  for (const cls of ordered) {
    if (!present.has(cls)) throw new Error(`VEHICLE_CLASS_ORDER lists an unused class: "${cls}"`);
  }

  const seen = new Set<string>();
  for (const vehicle of VEHICLE_ARCHETYPES) {
    if (seen.has(vehicle.id)) throw new Error(`Duplicate vehicle archetype id: ${vehicle.id}`);
    seen.add(vehicle.id);

    // `xxxEn` being *present* is already enforced by the type; an empty
    // string still satisfies that type and would render as a blank card in
    // English mode, silently, for whoever happens to have the toggle on.
    if (!vehicle.commercialTypeEn.trim()) throw new Error(`${vehicle.id}: commercialTypeEn is empty`);
    if (!vehicle.marketNamesEn.trim()) throw new Error(`${vehicle.id}: marketNamesEn is empty`);
    if (!vehicle.notesEn.trim()) throw new Error(`${vehicle.id}: notesEn is empty`);
  }
}

assertClassOrderIntegrity();
