/**
 * Taksonomi kendaraan komersial Indonesia, 61 archetype.
 *
 * Sumbernya adalah riset armada bertanggal 5 Agustus 2026 yang menyandarkan
 * setiap angka pada regulasi Indonesia (PP 55/2012, PP 79/2013, UU 22/2009,
 * Kepmen PUPR 176/KPTS/M/2025, Permenhub 60/2019) dan spesifikasi resmi OEM.
 * Register sumber lengkapnya ada di `src/content/reference/sources.ts`.
 *
 * Satu prinsip mengatur seluruh berkas ini, dan mengabaikannya membuat data ini
 * berbahaya alih-alih berguna: **nama pasar bukan kelas kapasitas.** "CDD",
 * "fuso", "tronton", dan "wingbox" adalah sebutan dagang, bukan kategori
 * hukum. Tidak ada satu pun angka payload universal yang melekat padanya.
 * Kapasitas sesungguhnya sebuah unit hanya bisa dibaca dari STNK/KIR/SRUT-nya,
 * dari JBI/JBKI yang berlaku, dan dari berat kosong setelah karoseri terpasang.
 *
 * Karena itu setiap angka di sini masuk sebagai **rentang perencanaan**, bukan
 * spesifikasi. Rentang menyatakan ketidakpastian yang memang ada; satu angka
 * tunggal akan menyembunyikannya, dan yang menanggung akibatnya adalah sopir di
 * jembatan timbang.
 *
 * DIHASILKAN dari Master_Kendaraan_Komersial_Indonesia_Cost_per_KM_2026.xlsx.
 * Sunting sumber datanya, bukan berkas ini.
 */

export interface Range {
  min: number;
  max: number;
}

export interface VehicleArchetype {
  /** Kunci stabil, sekaligus anchor tautan pada tabel referensi. */
  id: string;
  /**
   * Already English in the source data ("Light Commercial", "Heavy Truck", ...),
   * so it doubles as its own English label. No `mainClassEn` twin exists
   * because there is nothing left to translate.
   */
  mainClass: string;
  /** Deskripsi teknis netral dalam bahasa Indonesia, tidak memakai nama dagang. */
  commercialType: string;
  commercialTypeEn: string;
  /** Sebutan pasar yang dipakai sehari-hari -- ini yang orang ketik di mesin pencari. */
  marketNames: string;
  marketNamesEn: string;
  /** Kategori kendaraan barang menurut PP 55/2012: N1, N2, N3, atau kategori trailer O. */
  legalCategory: string;
  unitForm: string;
  axleConfig: string;
  totalAxles: string;
  overallLengthM?: number;
  /** Golongan penyeberangan -- ditentukan panjang keseluruhan, bukan jumlah gandar. */
  ferryClass: string;
  /** Golongan tol -- ditentukan jenis kendaraan dan jumlah gandar, bukan panjang. */
  tollClass: string;
  body: string;
  /** Dimensi ruang muat khas dalam meter, bila bodinya memang berbentuk ruang. */
  cargo?: { length: number; width: number; height: number };
  /** Rentang volume perencanaan (m3). Kosong untuk bodi yang tidak diukur dengan volume. */
  planningVolume?: Range;
  /** Rentang payload perencanaan (ton). Bukan rating legal. */
  planningPayload: Range;
  /** Rating GVW/GCW pabrikan (ton) sebagaimana ditulis sumber. */
  rating: string;
  roadClass: string;
  scope: string;
  dataStatus: string;
  notes: string;
  notesEn: string;
  sources: string[];
}

